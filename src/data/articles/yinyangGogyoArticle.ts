人体は静止した物体ではなく、体温、血圧、ホルモン濃度、自律神経トーンが絶え間なく揺らぐ動的システムです。古代の医家は、温度計や血液検査が存在しない時代に、この動的システムが「寒い方向（低代謝）」へ向かっているのか、「熱い方向（高代謝）」へ向かっているのかを評価するため、連続量を定性的に二値化したのです。

