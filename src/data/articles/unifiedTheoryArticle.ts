「現代医学は分子・局所だけ」「東洋医学は全身・機能だけ」と分けると、実際の医療を狭く理解してしまいます。現代の診療にも、生活機能、心理社会的背景、予防、長期の再評価があります。伝統医学にも、局所の観察や症状をもとにする治療があります。

