・ **超音波エラストグラフィ**：腹壁各層や肝臓の硬度（弾性率）をリアルタイムに画像・数値化。
・ **触診圧力センサー**：押し込み速度、接触面積、深度ごとの反発力を計測し、触診圧を標準化。
・ **表面筋電図（EMG）**：腹証として触知された硬さが、実際の運動単位活動電位の増加と一致することを検証。

