function article(code: FootCode, copy: Copy): AcupointAtlasArticle {
  const { view, pdfPage } = footLandmarks[code];
  const family = code.slice(0, 2) as keyof typeof readings;
  const order = Number(code.slice(2));
  const nearFirst = Math.min(Math.max(1, order - 1), lastOrder[family] - 2);
  return {
    titleTopic: "場所・見つけ方と注意点",
    description: `${copy.name}（${code.toUpperCase()}）の位置を、${copy.region}を目印に図解。近くのツボとの違い、WHO標準部位と自分で触れる際の注意点を紹介します。`,
    locationSummary: `${copy.region}。`,
    meridianReading: readings[family],
    regionLabel: copy.region,
    lead: copy.lead,
    location: [setup[view], copy.find, copy.distinguish],
    traditionalTitle: "近くのツボとの見分け方",
    traditional: [copy.context],
    selfCare: [copy.care ?? gentleCare],
    visualOnly: true,
    cautions: [gentleCautions],
    expert: [copy.expert],
    safetyWarning: copy.warning,
    symptomLinks: [{ href: "/symptoms", label: "気になる症状から受診の目安を探す" }],
    relatedPoints: copy.compare,
    sources: [
      { name: `WHO西太平洋地域事務局『WHO標準経穴部位』p.${pdfPage - 9}（PDF）`, url: `${who}#page=${pdfPage}`,
        scope: `${copy.name}の標準部位と、骨・腱・関節の位置関係を照合。` },
      careSource, injurySource, ...(copy.sources ?? []),
    ],
    illustration: {
      region: anklePoints.has(code) ? "ankle" : "dorsalFoot",
      bodyLabel: `左右の${anklePoints.has(code) ? "足首まわり" : viewLabels[view]}`,
      closeUpAlt: `${copy.name}（${code.toUpperCase()}）の位置。丸印は${copy.region}。`,
      closeUpCaption: `${copy.region}にある丸印が${copy.name}です。`,
      meridianStart: nearFirst, meridianEnd: nearFirst + 2,
      meridianCaption: `${copy.name}（${code.toUpperCase()}）と、同じ経絡の前後の番号を示します。`,
    },
  };
}

