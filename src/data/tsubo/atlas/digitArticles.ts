function digitArticle(code: DigitCode, copy: DigitCopy): AcupointAtlasArticle {
  const { part, position, pdfPage } = digitLandmarks[code];
  const number = Number(code.slice(2));
  const side = copy.regionLabel;
  const tip = position === "tip";
  const standard = tip
    ? "WHO標準の主たる位置は、中指の先端の中央です。"
    : `WHO標準の目安は、${side}の爪の角から根元寄りに0.1指寸（しすん）です。指寸はその人の指を基準にした単位です。図では爪の横の縁を延ばした線と、爪の根元を通る横線の交わる位置を示しました。`;
  return {
    titleTopic: copy.titleTopic ?? (tip ? "指先での場所と注意点" : "爪を目印にした探し方と注意点"),
    description: copy.lead,
    meridianReading: copy.meridianReading,
    regionLabel: side,
    lead: copy.lead,
    safetyWarning: copy.safetyWarning,
    location: copy.location,
    traditional: [copy.traditional],
    selfCare: [copy.selfCare],
    cautions: [copy.cautions],
    expert: [standard, copy.expert],
    relatedPoints: copy.relatedPoints,
    symptomLinks: [copy.symptomLink ?? symptomIndex],
    sources: [
      { name: `WHO西太平洋地域事務局『WHO標準経穴部位』p.${pdfPage - 9}（PDF）`,
        url: `https://iris.who.int/server/api/core/bitstreams/d98c1c98-3fbf-4e4e-8c9a-1bbe72ccd00e/content#page=${pdfPage}`,
        scope: `${copy.name}（${code.toUpperCase()}）の標準位置と図の向き・目印を照合。` },
      classicalTable, ...copy.sources,
    ],
    illustration: {
      region: part === "hand" ? "finger" : "toe",
      bodyLabel: part === "hand" ? "左右の手の指先" : "左右の足の指先",
      closeUpAlt: `${copy.name}（${code.toUpperCase()}）。①で対象の指の骨を示し、拡大図の丸印で${side}${tip ? "を示す。" : "にある爪の根元の角を示す。"}`,
      closeUpCaption: tip ? "①は中指。丸印は中指の先端の中央です。" : `①で指を確かめたら、拡大図で${side}を見ます。丸印は爪の根元の角のすぐきわです。`,
      meridianStart: number === 1 ? 1 : number - 2,
      meridianEnd: number === 1 ? 3 : number,
      meridianCaption: copy.meridianCaption,
    },
  };
}

