function onAbdomen() {
  return onView("abdomen", bellyRows.map(([code, outward, above]) => {
    const level = above === 0 ? "おへその中心と同じ高さ" : `おへその中心から${above > 0 ? "上" : "下"}へ${Math.abs(above)}寸`;
    const across = outward ? `そこからおなかの中央線の横へ${outward}寸` : "おなかの中央線上";
    const direction = above > 0 ? "みぞおち・胸の方" : "下腹部・脚の方";
    const reference = above > 0 ? "みぞおち上の胸骨のつなぎ目" : "下腹部の下端の恥骨";
    const guide = code === "cv8"
      ? "おへその中心を図の丸印で見ます。すぐ上に水分、すぐ下に陰交があり、同じ高さで横にずれると肓兪・天枢・大横の列になります。おへその穴の内側に指を入れる必要はありません。"
      : `まずおへその中央を確認し、${above === 0 ? "そこから真横へ同じ高さを保ちます。" : `${reference}までの区間を図で見て、${direction}へ${Math.abs(above)}寸の高さを先に取ります。`}${outward === 0 ? "線の左右にずれず、おへそを通る中央線に印があります。" : `その高さのまま、中央線から横へ${outward}寸の列を見ます。${outward === 0.5 ? "おへそに近い腎経の列で、胃経の列より中央寄りです。" : outward === 2 ? "中央寄りの腎経と、外側の脾経の列の間です。" : "胃経の列より外側です。"}`}`;
    return [code, 106 + outward * 17, 144 - above * (above < 0 ? 19 : 14),
      above === 0 ? "navel abdomenMid" : above > 0 ? "navel chestBottom" : "navel pubis",
      code === "cv8" ? "おへその中央" : `${level}で、${across}`, guide];
  }));
}

