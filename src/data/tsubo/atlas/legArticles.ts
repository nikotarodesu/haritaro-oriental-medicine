function article(code: LegCode, copy: ArticleCopy): AcupointAtlasArticle {
  const point = legLandmarks[code];
  const { view, pdfPage } = point;
  const family = code.slice(0, 2) as keyof typeof readings;
  const order = Number(code.slice(2));
  const popliteal = view === "posterior" && point.y === poplitealY;
  const calf = (view === "posterior" && !popliteal) || code === "ki9";
  const viewName = popliteal ? "ひざの裏" : code === "ki9" ? "ふくらはぎの内側" : calf ? "ふくらはぎの後ろ" : viewNames[view];
  return {
    titleTopic: `${viewName}の位置図と注意点`,
    description: `${copy.name}（${code.toUpperCase()}）の場所は、${copy.label}です。${viewName}の図で近くのツボと見比べ、WHO標準の位置と触れるときの注意も確認できます。`,
    locationSummary: `${copy.label}。${"cun" in point ? "寸は体の区間を等分した位置の目安です。" : ""}`,
    meridianReading: readings[family],
    regionLabel: copy.label,
    lead: copy.lead,
    location: [setup[view], copy.find, copy.distinguish],
    traditionalTitle: code === "sp6" ? "伝統的な使われ方" : "近くのツボとの見分け方",
    traditional: [copy.context],
    visualOnly: true,
    selfCare: [view === "posterior" || code === "ki9" ? posteriorCare : gentle],
    cautions: [calf ? calfCaution : workCaution],
    expert: ["WHO標準では" + copy.expert + ("cun" in point ? units : "")],
    safetyWarning: [copy.warning, calf ? calfWarning : undefined].filter(Boolean).join(" ") || undefined,
    relatedPoints: copy.links,
    symptomLinks: [{ href: view === "knee" || popliteal ? "/symptoms/knee-joint-pain" : "/symptoms", label: view === "knee" || popliteal ? "ひざの痛み・受診の目安" : "気になる症状から受診の目安を探す" }],
    sources: [
      { name: `WHO西太平洋地域事務局『WHO標準経穴部位』p.${pdfPage - 9}（PDF）`, url: `${who}#page=${pdfPage}`, scope: `${copy.name}の位置、骨や腱などの目印を照合。` },
      ...genericSources, ...(calf ? [clot, urgent] : []), ...(code === "sp6" ? [pregnancy] : []), ...(code === "ki1" ? [urgent] : []),
    ],
    illustration: {
      region: view === "sole" ? "sole" : view === "shinFront" ? "anterolateralLowerLeg" : view === "knee" || popliteal ? "knee" : "calf",
      bodyLabel: `左右の${viewName}`,
      closeUpAlt: `${viewName}の拡大図。${copy.label}の丸印が${copy.name}（${code.toUpperCase()}）。`,
      closeUpCaption: `拡大図では、${copy.label}に${copy.name}の丸印を付けています。`,
      meridianStart: Math.max(1, order - 1), meridianEnd: Math.max(3, order + 1),
      meridianCaption: `${copy.name}（${code.toUpperCase()}）と、同じ経絡に並ぶ前後のツボです。`,
    },
  };
}

