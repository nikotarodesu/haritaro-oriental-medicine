assert.equal(recommend({...base,quizResults:{q1:{...due,kind:'acupoint',nextReviewDate:undefined}}}).href,'/kokushi#learning-review');
assert.equal(recommend({...base,caseNeeds:[{...focus,href:'https://other.example'}]}).kind,'course');
