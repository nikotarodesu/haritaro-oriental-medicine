/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS offline regression runner. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const cache = new Map();
function load(relative) {
  let file = path.resolve(root, relative);
  if (!file.endsWith('.ts')) file += '.ts';
  if (cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file, exports);
  const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const localRequire = id => id.startsWith('@/') ? load('src/' + id.slice(2)) : id.startsWith('.') ? load(path.resolve(path.dirname(file), id)) : require(id);
  vm.runInNewContext(js, { exports, require: localRequire, process, URL, console }, { filename: file });
  return exports;
}
const { getLearningRecommendation: recommend } = load('src/utils/learningRecommendation');
const { LEARNING_COURSES } = load('src/data/learningCourses');
const lectures = LEARNING_COURSES.flatMap(course => course.steps.map(step => ({id: step.lectureId, title: step.title})));
lectures.push({id:'lecture-diagnosis-1',title:'診察の講義'});
const base = {lectures,completed:{},lastVisitedLectureId:null,quizResults:{},caseNeeds:[],caseAttempts:[],today:'2026-10-04'};
assert.equal(recommend(base).href,'/curriculum/lecture-intro-1?course=oriental-medicine-introduction');
const focus = {caseId:'fatigue-reasoning',caseTitle:'疲労',focusId:'comparison',title:'比較',reason:'基準を確認',href:'/kokushi?focus=comparison#learning-focus-review',safetyReviewRequired:false,answeredAt:'2026-10-04T00:00:00.000Z'};
const safety = {...focus,focusId:'safety-check',href:'/kokushi?focus=safety-check#learning-focus-review',safetyReviewRequired:true};
const due = {questionId:'q1',lectureId:lectures[0].id,isCorrect:false,answeredAt:'2026-10-03T00:00:00.000Z',nextReviewDate:'2026-10-04'};
assert.equal(recommend({...base,caseNeeds:[focus,safety],quizResults:{q1:due}}).kind,'safety');
assert.equal(recommend({...base,caseNeeds:[focus],quizResults:{q1:due}}).kind,'due');
