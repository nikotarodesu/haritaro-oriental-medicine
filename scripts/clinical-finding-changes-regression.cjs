/* eslint-disable @typescript-eslint/no-require-imports -- Verify precise finding transactions and safe one-operation restoration. */
const assert = require('node:assert/strict');
const { createDataLoader } = require('./data-loader.cjs');
const load = createDataLoader();
const { clinicalExaminationPatch, clinicalFindingEdit, canUndoClinicalFindingEdit, undoClinicalFindingEdit, validClinicalFindingHistory } = load('src/utils/clinicalFindingChanges');
const plain = value => JSON.parse(JSON.stringify(value));

const before = { observations: { fatigue: 'present', greasyCoat: 'present' }, examination: { coatColor: '黄', coatThickness: '厚い', coatTexture: '膩苔（きめ細かく粘る）', coatMoisture: '潤っている' } };
const after = clinicalExaminationPatch(before, 'coatColor', '苔を認めない');
const edit = clinicalFindingEdit(before, after, { kind: 'examination', id: 'coatColor' }, 1);
assert(edit && edit.items.length === 4, 'Every linked native coating field is visible in the same transaction');
assert.equal(edit.items.filter(item => item.linked).length, 3);
assert(edit.items.every(item => item.after === '苔を認めない'));
assert(!edit.items.some(item => item.label === '膩苔'), 'Derived flags do not duplicate native-field history rows');
assert(canUndoClinicalFindingEdit(after, edit));
assert.deepEqual(plain(undoClinicalFindingEdit(after, edit)), before);
const unrelated = { ...after, observations: { ...after.observations, cold: 'present' }, examination: { ...after.examination, pulseDepth: '中間で触れる' } };
const restored = undoClinicalFindingEdit(unrelated, edit);
assert.equal(restored.observations.cold, 'present');
assert.equal(restored.examination.pulseDepth, '中間で触れる');
assert.equal(restored.examination.coatThickness, '厚い');
const laterEdit = { ...after, examination: { ...after.examination, coatThickness: '薄い' } };
assert(!canUndoClinicalFindingEdit(laterEdit, edit));
assert.equal(undoClinicalFindingEdit(laterEdit, edit), null, 'Later edits of a linked field cannot be silently overwritten');
assert.equal(undoClinicalFindingEdit(after, { ...edit, undone: true }), null);

const legacy = { observations: { fixedPain: 'present' } };
const changedLegacy = clinicalExaminationPatch(legacy, 'painLocation', '移動する');
assert.equal(changedLegacy.examination.painQuality, '刺すような痛み');
const legacyEdit = clinicalFindingEdit(legacy, changedLegacy, { kind: 'examination', id: 'painLocation' }, 2);
assert.equal(legacyEdit.items.length, 1, 'Materializing the unchanged legacy quality is not reported as a user change');
assert.equal(legacyEdit.items[0].before, '固定している');
const originalLegacy = undoClinicalFindingEdit(changedLegacy, legacyEdit);
assert.equal(originalLegacy.examination, undefined);
assert.deepEqual(plain(originalLegacy.observations), legacy.observations);
const original = { observations: {} }, observed = { observations: { fatigue: 'present' } };
const signEdit = clinicalFindingEdit(original, observed, { kind: 'observation', id: 'fatigue' }, 3);
assert.deepEqual(plain(signEdit.items), [{ label: '疲労・気力低下', before: '未確認', after: 'あり', linked: false }]);
assert.deepEqual(plain(undoClinicalFindingEdit(observed, signEdit)), original);
assert.equal(clinicalFindingEdit(original, original, { kind: 'observation', id: 'fatigue' }, 4), null);
assert.equal(clinicalFindingEdit(original, { observations: { fatigue: 'unknown' } }, { kind: 'observation', id: 'fatigue' }, 5), null, 'Semantic no-ops do not clutter history');
const detailedBefore = { observations: {}, examination: { tongueColor: '淡白', pulseStrength: '弱い・無力' } };
const detailedAfter = clinicalExaminationPatch(detailedBefore, 'tongueColor', '紅');
const tongueEdit = clinicalFindingEdit(detailedBefore, detailedAfter, { kind: 'examination', id: 'tongueColor' }, 6);
assert.deepEqual(plain(tongueEdit.items), [{ label: '舌体の色', before: '淡白', after: '紅', linked: false }], 'Normalizing an existing pulse flag is not a change of the pulse observation');
const laterPulse = clinicalExaminationPatch(detailedAfter, 'pulseStrength', '強い・有力');
assert(canUndoClinicalFindingEdit(laterPulse, tongueEdit));
const restoredTongue = undoClinicalFindingEdit(laterPulse, tongueEdit);
assert.equal(restoredTongue.examination.tongueColor, '淡白');
assert.equal(restoredTongue.examination.pulseStrength, '強い・有力');
assert.equal(restoredTongue.observations.weakPulse, 'absent', 'Undo cannot restore a normalized but unrelated pulse flag');
const { parseClinicalEncounter, emptyClinicalEncounter, clinicalEncounterFingerprint, clinicalEncounterSaveState } = load('src/utils/clinicalEncounter');
const persisted = plain([edit, legacyEdit, signEdit, tongueEdit]);
assert(validClinicalFindingHistory(persisted));
const draft = { ...emptyClinicalEncounter(), ...after, findingHistory: plain([edit]) };
const reloadedDraft = parseClinicalEncounter(plain(draft));
assert.deepEqual(plain(undoClinicalFindingEdit(reloadedDraft, reloadedDraft.findingHistory[0])), before);
assert.equal(clinicalEncounterFingerprint(draft), clinicalEncounterFingerprint({ ...draft, findingHistory: undefined }), 'History is draft metadata, not a change to saved note contents');
const saved = { ...draft, savedNoteId: 'test-note', savedFingerprint: clinicalEncounterFingerprint(draft) };
assert.equal(clinicalEncounterSaveState({ ...saved, findingHistory: plain([{ ...edit, undone: true }]) }), 'saved');
assert(parseClinicalEncounter(plain(emptyClinicalEncounter())), 'Existing drafts without history stay readable');
for (const invalid of [null, {}, Array(21).fill(edit), [edit, edit], [{ ...edit, id: -1 }], [{ ...edit, id: Number.MAX_SAFE_INTEGER }], [{ ...edit, undone: 'true' }], [{ ...edit, deltas: [] }], [{ ...edit, items: [{ label: '任意のラベル', before: '', after: '', linked: false }] }], [{ ...edit, deltas: [{ kind: 'examination', id: '__proto__', before: '', after: '' }] }], [{ ...edit, deltas: [{ kind: 'examination', id: 'coatColor', after: '不正な選択肢' }] }], [{ ...edit, deltas: [{ kind: 'observation', id: 'fatigue', after: 'yes' }] }]]) {
  assert(!validClinicalFindingHistory(invalid));
  const recovered = parseClinicalEncounter({ ...draft, findingHistory: invalid });
  assert(recovered && recovered.findingHistory === undefined);
  assert.deepEqual(plain(recovered.examination), plain(draft.examination), 'A damaged history cannot discard the current findings');
}
console.log('Clinical finding changes: exact before/after history, linked coating changes, derived-field deduplication, legacy composites, one-operation restoration, unrelated-field retention and stale-edit protection passed.');
