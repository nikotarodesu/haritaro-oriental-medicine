/* eslint-disable @typescript-eslint/no-require-imports -- Build-time public route catalog. */
const fs = require('node:fs');
const path = require('node:path');
const { createDataLoader } = require('./data-loader.cjs');
const root = path.resolve(__dirname, '..');

function generatePublicGuideRoutes() {
  const load = createDataLoader();
  const { SYMPTOMS } = load('src/data/symptomData');
  const { CLINICAL_COMPLAINTS } = load('src/data/clinicalWorkflow');
  const paths = (items, key, prefix) => {
    const slugs = items.map(item => item[key]);
    if (slugs.some(slug => typeof slug !== 'string' || !/^[a-z0-9-]{1,80}$/.test(slug)) || new Set(slugs).size !== slugs.length) {
      throw new Error('Public guide slugs must be unique, explicit and URL safe.');
    }
    return slugs.map(slug => prefix + slug);
  };
  return '// Generated by scripts/generate-public-guide-routes.cjs from published guide data.\n'
    + '// Keep the analytics bundle small; do not import medical guide bodies here.\n'
    + `export const PUBLIC_SYMPTOM_PATHS = ${JSON.stringify(paths(SYMPTOMS, 'id', '/symptoms/'), null, 2)} as const;\n`
    + `export const PUBLIC_CLINICAL_GUIDE_PATHS = ${JSON.stringify(paths(CLINICAL_COMPLAINTS, 'slug', '/clinical/symptoms/'), null, 2)} as const;\n`;
}

if (require.main === module) {
  const target = path.join(root, 'src/config/publicGuideRoutes.ts');
  const content = generatePublicGuideRoutes();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) {
      throw new Error('Public guide routes are stale. Run npm run generate:guides.');
    }
    console.log('Passed: analytics routes match all published symptom and clinical guides.');
  } else {
    fs.writeFileSync(target, content, 'utf8');
    console.log('Generated public guide routes.');
  }
}

module.exports = { generatePublicGuideRoutes };
