/* eslint-disable @typescript-eslint/no-require-imports -- Offline rendering checks. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const root = path.resolve(__dirname, '..');
const cache = new Map();
function load(relative) {
  let file = path.resolve(root, relative);
  if (!path.extname(file)) file += fs.existsSync(file + '.tsx') ? '.tsx' : '.ts';
  if (cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file, exports);
  const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), { fileName: file, compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
  const localRequire = id => {
    if (id === 'next/link') return ({ href, children, ...props }) => React.createElement('a', { href, ...props }, children);
    if (['@/components/CurriculumDiagram', '@/components/EastWestTermSwitch'].includes(id)) return () => null;
    if (id === './CitationBadge') return ({ displayNumber, targetAnchorId }) => React.createElement('sup', { 'data-reference': targetAnchorId }, displayNumber);
    if (id.startsWith('@/')) return load('src/' + id.slice(2));
    if (id.startsWith('.')) return load(path.resolve(path.dirname(file), id));
    return require(id);
  };
  vm.runInNewContext(js, { exports, require: localRequire, URL, console, process }, { filename: file });
  return exports;
}
const { CURRICULUM_DATA } = load('src/data/curriculumData');
const { parseMarkdownBlocks } = load('src/utils/markdownParser');
const { CURRICULUM_CONCEPT_ART, getCurriculumConceptArt } = load('src/components/curriculum/CurriculumConceptArt');
const MarkdownBody = load('src/components/MarkdownBody').default;
const { CURRICULUM_READING_INSERTS } = load('src/data/curriculumReadingGuides');
const lectures = CURRICULUM_DATA.flatMap(series => series.lectures);
const publishedLectures = lectures.filter(lecture => lecture.isPublished);
assert.equal(Object.keys(CURRICULUM_CONCEPT_ART).length, publishedLectures.length, 'one illustration for every published lecture');
for (const lecture of publishedLectures) assert(CURRICULUM_CONCEPT_ART[lecture.id], lecture.id + ': wordless artwork coverage');
const headingIds = html => Array.from(html.matchAll(/<h[1-4][^>]*id="([^"]+)"/g), match => match[1]).join('|');
let count = 0;
for (const [id, specification] of Object.entries(CURRICULUM_CONCEPT_ART)) {
  const lecture = lectures.find(item => item.id === id);
  assert(lecture?.isPublished, id + ': artwork belongs to a published lecture');
  const source = lecture.contentMarkdown;
  const blocks = parseMarkdownBlocks(source);
  assert(!/📘|⚠️|🔬|出典|参考文献/.test(specification.afterHeading), id + ': main reading section, not supplementary material');
  assert.equal(blocks.filter(block => block.type === 'h2' && block.content === specification.afterHeading).length, 1, id + ': unique actual section placement');
  const conceptArt = getCurriculumConceptArt(id);
  assert(conceptArt?.node, id + ': artwork generated');
  const art = renderToStaticMarkup(conceptArt.node);
  const svg = art.match(/<svg\b[^>]*>[\s\S]*?<\/svg>/)?.[0];
  assert(svg, id + ': a vector illustration is rendered');
  assert(art.includes('role="img"') && /aria-label=|<title\b/.test(art), id + ': accessible image meaning');
  assert(!/<text\b|<foreignObject\b|<figcaption\b/.test(art), id + ': no visible SVG text or prose');
  assert(!/<image\b|<script\b|<animate\b|NaN|Infinity/.test(art), id + ': static, valid vector artwork');
  assert.equal(svg.replace(/<(title|desc)\b[^>]*>[\s\S]*?<\/\1>/g, '').replace(/<[^>]*>/g, '').trim(), '', id + ': artwork itself remains wordless');
  const readingGuides = art.match(/<details\b[^>]*>[\s\S]*?<\/details>/g) || [];
  assert.equal(readingGuides.length, 1, id + ': one optional reading guide outside the SVG');
  const guide = readingGuides[0];
  assert(!/<details\b[^>]*\sopen(?:[\s=>])/.test(guide), id + ': the reading guide starts closed');
  assert.match(guide, /<summary\b[^>]*>図の読み方<\/summary>/, id + ': the guide has a clear keyboard-operable summary');
  const description = renderToStaticMarkup(React.createElement(React.Fragment, null, specification.description));
  assert(guide.includes(description), id + ': the full authored definition is available to readers');
  assert(!svg.includes(guide), id + ': prose is outside the image');
  assert.equal(art.replace(svg, '').replace(guide, '').replace(/<[^>]*>/g, '').trim(), '', id + ': optional guide is the only surrounding visible prose');
  assert(!/(?:d|transform|cx|cy)="[^"]*\.\d{4,}/.test(art), id + ': derived SVG geometry avoids server/browser float serialization drift');
  const base = renderToStaticMarkup(React.createElement(MarkdownBody, { contentMarkdown: source, idPrefix: 'lecture' }));
  const illustrated = renderToStaticMarkup(React.createElement(MarkdownBody, { contentMarkdown: source, idPrefix: 'lecture', conceptArt }));
  assert.equal(headingIds(illustrated), headingIds(base), id + ': original heading anchors preserved');
  const hasArtwork = illustrated.includes(art);
  assert.equal((illustrated.match(/class="[^"]*curriculum-concept-art/g) || []).length, hasArtwork ? 1 : 0, id + ': no repeated artwork');
  assert.equal(illustrated.replace(art, ''), base, id + ': authored body rendering unchanged apart from artwork');
  const collapsed = renderToStaticMarkup(React.createElement(MarkdownBody, { contentMarkdown: source, idPrefix: 'lecture', conceptArt, collapseAdvanced: true }));
  const artworkMarker = `<span data-wordless-art="${id}"></span>`;
  assert.equal(collapsed.includes(art), hasArtwork, id + ': supplementary sections do not change visual selection');
  if (hasArtwork) assert(collapsed.replace(art, artworkMarker).replace(/<details\b[\s\S]*?<\/details>/g, '').includes(artworkMarker), id + ': illustration visible without opening supplementary sections');
  count++;
}
assert.equal(getCurriculumConceptArt('unknown-lecture'), null, 'unmapped lectures remain unchanged');
const bloodLesson = lectures.find(lecture => lecture.id === 'lecture-qiblood-2');
const bloodWithFigures = renderToStaticMarkup(React.createElement(MarkdownBody, { contentMarkdown: bloodLesson.contentMarkdown, conceptArt: getCurriculumConceptArt(bloodLesson.id), readingInserts: CURRICULUM_READING_INSERTS[bloodLesson.id] }));
assert.equal((bloodWithFigures.match(/data-reading-figure=/g) || []).length, 1, 'Blood lesson retains its instructional comparison');
assert(!bloodWithFigures.includes('curriculum-concept-art'), 'Same-section artwork does not repeat the blood comparison');
assert(bloodWithFigures.includes('data-reading-exercise='), 'The retained figure has an optional worked answer');
console.log(`Passed: ${count} artwork definitions with accessible names and stable anchors; redundant same-section visuals are omitted and the blood comparison keeps a hidden worked answer.`);
